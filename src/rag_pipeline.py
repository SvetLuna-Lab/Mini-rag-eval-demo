"""
Minimal RAG pipeline on top of DocumentIndexer.

This module defines:

- RagAnswer : dataclass with question, answer, contexts, scores
- SimpleLLMStub : fake LLM that "answers" using retrieved texts
- RagPipeline : glue that runs retrieval + generation
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Sequence, Tuple

from .indexer import Document, DocumentIndexer


@dataclass
class RagAnswer:
    """
    Container for a single RAG run.

    Attributes
    ----------
    question : str
        Original user question.
    answer : str
        Generated answer (from the LLM stub).
    contexts : List[Document]
        Retrieved documents used as context.
    scores : List[float]
        Similarity scores for each retrieved document.
    """

    question: str
    answer: str
    contexts: List[Document]
    scores: List[float]


class SimpleLLMStub:
    """
    Ultra-simple LLM stub.

    Instead of calling a real model, this class just stitches together
    the most relevant snippets and wraps them in a short template.
    """

    def __init__(self, max_chars_per_context: int = 300) -> None:
        self.max_chars_per_context = max_chars_per_context

    def _shorten(self, text: str) -> str:
        text = text.replace("\n", " ").strip()
        if len(text) > self.max_chars_per_context:
            return text[: self.max_chars_per_context - 3] + "..."
        return text

    def generate(self, question: str, contexts: Sequence[Document]) -> str:
        """
        Produce a pseudo-answer using retrieved contexts.

        Parameters
        ----------
        question : str
            User question.
        contexts : Sequence[Document]
            Documents returned by the retriever.

        Returns
        -------
        str
            A synthetic answer string.
        """
        if not contexts:
            return (
                "I could not find any relevant documents for this question yet. "
                "Please try to add more data to the corpus."
            )

        snippets = [self._shorten(doc.text) for doc in contexts]
        joined = "\n\n".join(f"[{doc.doc_id}] {snippet}" for doc, snippet in zip(contexts, snippets))

        return (
            "This is a synthetic RAG-style answer generated by a simple stub.\n\n"
            f"Question:\n{question}\n\n"
            "Based on the retrieved context, here is a summary:\n"
            f"{joined}"
        )


class RagPipeline:
    """
    Simple RAG pipeline: retrieval + fake generation.

    Usage
    -----
    pipeline = RagPipeline(indexer)
    result = pipeline.run(\"What is ...?\", top_k=3)
    """

    def __init__(self, indexer: DocumentIndexer, llm: SimpleLLMStub | None = None) -> None:
        if not indexer.is_ready():
            raise ValueError("Indexer must be fitted before constructing RagPipeline.")

        self.indexer = indexer
        self.llm = llm or SimpleLLMStub()

    def run(self, question: str, top_k: int = 3) -> RagAnswer:
        """
        Run the full RAG pipeline for a single question.

        Parameters
        ----------
        question : str
            User question.
        top_k : int, optional
            Number of documents to retrieve, by default 3.

        Returns
        -------
        RagAnswer
            Structured result containing answer and contexts.
        """
        retrieved: List[Tuple[Document, float]] = self.indexer.retrieve(question, top_k=top_k)
        contexts, scores = zip(*retrieved)

        answer_text = self.llm.generate(question, list(contexts))

        return RagAnswer(
            question=question,
            answer=answer_text,
            contexts=list(contexts),
            scores=list(scores),
        )
